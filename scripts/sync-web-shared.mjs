// apps/web is deployed on its own (own lock file), so it cannot import from the monorepo's shared package.
// This script copies the shared rules and the UI copy into apps/web/lib/generated.
//   node scripts/sync-web-shared.mjs          write the copies
//   node scripts/sync-web-shared.mjs --check  fail if the copies are out of date (used in CI)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "apps", "web", "lib", "generated");
const check = process.argv.includes("--check");

const header = "// GENERATED by scripts/sync-web-shared.mjs from packages/shared. Do not edit; edit the source and re-run the script.\n";

const files = [
  ["packages/shared/src/status.ts", "status.ts"],
  ["packages/shared/src/schemas.ts", "schemas.ts"],
  ["packages/shared/src/photoCheck.ts", "photoCheck.ts"],
];

const wanted = new Map();
for (const [src, name] of files) {
  // Turbopack resolves extensionless relative imports; the sources use ".js" for Node.
  const body = fs.readFileSync(path.join(root, src), "utf8").replace(/from "(\.\/[^"]+)\.js"/g, 'from "$1"');
  wanted.set(name, header + body);
}
wanted.set("index.ts", header + 'export * from "./status";\nexport * from "./schemas";\nexport * from "./photoCheck";\n');
wanted.set("copy.en.json", fs.readFileSync(path.join(root, "content/ui/en.json"), "utf8"));

let stale = [];
fs.mkdirSync(outDir, { recursive: true });
for (const [name, content] of wanted) {
  const target = path.join(outDir, name);
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
  if (current === content) continue;
  stale.push(name);
  if (!check) fs.writeFileSync(target, content);
}

if (check && stale.length) {
  console.error(`apps/web/lib/generated is out of date: ${stale.join(", ")}. Run: node scripts/sync-web-shared.mjs`);
  process.exit(1);
}
console.log(stale.length ? `updated: ${stale.join(", ")}` : "apps/web/lib/generated is up to date");
